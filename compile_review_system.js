const fs = require('fs');
const path = require('path');

const SKILL_TEMPLATE_PATH = 'C:\\Users\\firem\\.gemini\\config\\skills\\universal-exam-review-builder\\resources\\spa_template.html';
const WORKSPACE_DIR = __dirname;

const questionsPath = path.join(WORKSPACE_DIR, 'exam_questions.json');
const subjectConfigPath = path.join(WORKSPACE_DIR, 'subject_config.json');
const tailwindPath = path.join(WORKSPACE_DIR, 'tailwind.min.js');

const questions = JSON.parse(fs.readFileSync(questionsPath, 'utf-8'));
const subjectConfig = JSON.parse(fs.readFileSync(subjectConfigPath, 'utf-8'));
const templateHtml = fs.readFileSync(SKILL_TEMPLATE_PATH, 'utf-8');

console.log(`[1/4] Loaded ${questions.length} questions and subject configuration.`);

// Validation
const validCategories = new Set(subjectConfig.categories.map(c => c.name));
const errors = [];

questions.forEach((q, idx) => {
  const prefix = `[Q#${idx + 1} (${q.id || 'NO_ID'})]`;
  if (!q.id) errors.push(`${prefix} Missing 'id'`);
  if (!q.question) errors.push(`${prefix} Missing 'question'`);
  if (!Array.isArray(q.options) || q.options.length !== 4) errors.push(`${prefix} 'options' must be array of 4`);
  if (!q.answer) errors.push(`${prefix} Missing 'answer'`);
  if (!validCategories.has(q.category)) errors.push(`${prefix} Invalid category: ${q.category}`);
  if (!Array.isArray(q.algorithm_path) || q.algorithm_path.length < 3) errors.push(`${prefix} 'algorithm_path' must have >= 3 steps`);
  if (!Array.isArray(q.key_triggers) || q.key_triggers.length < 2) errors.push(`${prefix} 'key_triggers' must have >= 2 items`);
  if (!q.confusion_trap || !q.confusion_trap.startsWith('• ')) errors.push(`${prefix} 'confusion_trap' must start with '• '`);
  if (!q.guideline_check || !q.guideline_check.startsWith('• ')) errors.push(`${prefix} 'guideline_check' must start with '• '`);
});

if (errors.length > 0) {
  console.error(`Validation found ${errors.length} errors:`);
  errors.forEach(e => console.error('  ', e));
  process.exit(1);
}
console.log(`[2/4] Validation passed! All ${questions.length} questions conform to the 4-dimensional pedagogy schema.`);

// 1. Generate exam_data.js
const dataJsContent = `// Auto-generated by universal-exam-review-builder
window.EXAM_SUBJECT_CONFIG = ${JSON.stringify(subjectConfig, null, 2)};
window.EXAM_QUESTIONS = ${JSON.stringify(questions, null, 2)};
`;
const dataJsPath = path.join(WORKSPACE_DIR, 'exam_data.js');
fs.writeFileSync(dataJsPath, dataJsContent, 'utf-8');
console.log(`[3/4] Wrote ${dataJsPath}`);

// 2. Generate index.html
const indexHtmlPath = path.join(WORKSPACE_DIR, 'index.html');
fs.writeFileSync(indexHtmlPath, templateHtml, 'utf-8');
console.log(`[3/4] Wrote ${indexHtmlPath}`);

// 3. Generate Single-File Offline Bundle
const bundleFilename = subjectConfig.bundleFilename || '消防設備師士_終極單一獨立版.html';
const bundlePath = path.join(WORKSPACE_DIR, bundleFilename);

let tailwindScript = '';
if (fs.existsSync(tailwindPath)) {
  const twContent = fs.readFileSync(tailwindPath, 'utf-8');
  tailwindScript = `<script>\n${twContent}\n</script>`;
} else {
  tailwindScript = '<script src="https://cdn.tailwindcss.com"></script>';
}

let bundleHtml = templateHtml.replace('<script src="tailwind.min.js"></script>', () => tailwindScript);
const inlineDataScript = `<script>\nwindow.EXAM_SUBJECT_CONFIG = ${JSON.stringify(subjectConfig)};\nwindow.EXAM_QUESTIONS = ${JSON.stringify(questions)};\n</script>`;
bundleHtml = bundleHtml.replace('<script src="exam_data.js"></script>', () => inlineDataScript);

fs.writeFileSync(bundlePath, bundleHtml, 'utf-8');
const bundleStat = fs.statSync(bundlePath);
console.log(`[4/4] Successfully built Single-File Offline Bundle: ${bundleFilename} (${(bundleStat.size / (1024 * 1024)).toFixed(2)} MB)`);
